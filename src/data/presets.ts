const QUESTIONS_PER_DECK = 10;
const SEEN_STORAGE_KEY = 'quizsync_seen_question_ids_v1';

const memorySeenByDeck = new Map<string, string[]>();

function loadSeenMap(): Record<string, string[]> {
  if (typeof window === 'undefined') {
    const out: Record<string, string[]> = {};
    for (const [k, v] of memorySeenByDeck.entries()) out[k] = v;
    return out;
  }
  try {
    const raw = localStorage.getItem(SEEN_STORAGE_KEY);
    if (!raw) return {};
    const parsed = JSON.parse(raw);
    return parsed && typeof parsed === 'object' ? (parsed as Record<string, string[]>) : {};
  } catch {
    return {};
  }
}

function saveSeenMap(map: Record<string, string[]>) {
  for (const [k, v] of Object.entries(map)) {
    memorySeenByDeck.set(k, v);
  }
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(SEEN_STORAGE_KEY, JSON.stringify(map));
  } catch {
    // Ignore storage quota errors
  }
}

export function markDeckQuestionsPlayed(deck: QuizDeck) {
  const poolIds = new Set(
    (PRESET_DECK_POOLS.find((p) => p.id === deck.id)?.questions ?? deck.questions).map(
      (q) => q.id
    )
  );
  const map = loadSeenMap();
  const prev = Array.isArray(map[deck.id]) ? map[deck.id] : [];
  const merged = new Set([...prev, ...deck.questions.map((q) => q.id)].filter((id) => poolIds.has(id)));
  map[deck.id] = Array.from(merged);
  saveSeenMap(map);
}

