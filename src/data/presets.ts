export function shuffleArray<T>(items: T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

export function shuffleQuestionOptions(question: QuizQuestion): QuizQuestion {
  const tagged = question.options.map((text, idx) => ({
    text,
    isCorrect: idx === question.correctIndex,
  }));
  const mixed = shuffleArray(tagged);
  const nextCorrect = mixed.findIndex((item) => item.isCorrect);
  return {
    ...question,
    options: mixed.map((item) => item.text),
    correctIndex: nextCorrect >= 0 ? nextCorrect : 0,
  };
}

export function rollDeckQuestions(deck: QuizDeck): QuizDeck {
  const poolSource = PRESET_DECK_POOLS.find((p) => p.id === deck.id);
  if (!poolSource) {
    const shuffled = shuffleArray(deck.questions).map(shuffleQuestionOptions);
    return {
      ...deck,
      questions: shuffled,
    };
  }

  const currentIds = new Set(deck.questions.map((q) => q.id));
  const seenMap = loadSeenMap();
  const prevSeen = Array.isArray(seenMap[deck.id]) ? seenMap[deck.id] : [];
  const seenSet = new Set([...prevSeen, ...currentIds]);

  let unseen = shuffleArray(
    poolSource.questions.filter((q) => !seenSet.has(q.id))
  );

  let selected: QuizQuestion[] = [];
  let nextSeenIds: string[];

  if (unseen.length >= QUESTIONS_PER_DECK) {
    selected = unseen.slice(0, QUESTIONS_PER_DECK);
    nextSeenIds = Array.from(
      new Set([...seenSet, ...selected.map((q) => q.id)])
    );
  } else {
    // Exhausted the 30-question cycle: carry over all remaining unseen questions,
    // reset history excluding the immediately previous round so zero consecutive repeats occur.
    const restPool = shuffleArray(
      poolSource.questions.filter(
        (q) => !currentIds.has(q.id) && !unseen.some((u) => u.id === q.id)
      )
    );
    selected = [...unseen, ...restPool].slice(0, QUESTIONS_PER_DECK);
    nextSeenIds = Array.from(
      new Set([...currentIds, ...selected.map((q) => q.id)])
    );
  }

  seenMap[deck.id] = nextSeenIds;
  saveSeenMap(seenMap);

  const finalQuestions = shuffleArray(selected).map(shuffleQuestionOptions);

  return {
    ...poolSource,
    questions: finalQuestions,
  };
}

export function rollAllPresetDecks(currentDecks: QuizDeck[]): QuizDeck[] {
  return currentDecks.map((deck) =>
    deck.isCustom ? deck : rollDeckQuestions(deck)
  );
}

export const PRESET_QUIZ_DECKS: QuizDeck[] = PRESET_DECK_POOLS.map((deck) => ({
  ...deck,
  questions: deck.questions.slice(0, QUESTIONS_PER_DECK),
}));
